-- ============================================================
-- MIGRACIÓN: Tablas Mercolleida para ML/RAG en Supabase
-- Datos del mercado porcino, vacuno, cereales y entrenamiento IA
-- ============================================================

-- 1. Sesiones semanales de la Lonja de Mercolleida
CREATE TABLE IF NOT EXISTS mercolleida_sesiones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_sesion DATE,
    fecha_publicacion DATE,
    semana SMALLINT,
    anio SMALLINT NOT NULL,
    tipo_reporte TEXT DEFAULT 'semanal',
    resumen_ejecutivo TEXT,
    factores_clave TEXT[],
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Cotizaciones de porcino en vivo (por sesión o año histórico)
CREATE TABLE IF NOT EXISTS cotizaciones_porcino (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id BIGINT REFERENCES mercolleida_sesiones(id) ON DELETE SET NULL,
    anio SMALLINT,
    mes TEXT,
    cerdo_normal NUMERIC(6,4),
    cerdo_selecto NUMERIC(6,4),
    cerdo_graso NUMERIC(6,4),
    cerda_desvieje NUMERIC(6,4),
    precio_medio NUMERIC(6,4),
    minimo NUMERIC(6,4),
    maximo NUMERIC(6,4),
    variacion_semanal_eur NUMERIC(6,4),
    variacion_semanal_pct NUMERIC(5,2),
    variacion_interanual_pct NUMERIC(5,2),
    tendencia TEXT,
    evento_clave TEXT,
    semanas_subidas SMALLINT,
    semanas_bajadas SMALLINT,
    semanas_repeticiones SMALLINT,
    hitos TEXT[],
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Cotizaciones de lechón base 20kg
CREATE TABLE IF NOT EXISTS cotizaciones_lechon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id BIGINT REFERENCES mercolleida_sesiones(id) ON DELETE SET NULL,
    anio SMALLINT,
    mes TEXT,
    precio_mercolleida_20kg NUMERIC(6,2),
    precio_zamora_segovia NUMERIC(6,2),
    precio_vic_18kg NUMERIC(6,2),
    maximo_semanal NUMERIC(6,2),
    variacion_semanal_eur NUMERIC(6,2),
    variacion_semanal_pct NUMERIC(5,2),
    tendencia TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Cotizaciones de vacuno (Monvac)
CREATE TABLE IF NOT EXISTS cotizaciones_vacuno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id BIGINT REFERENCES mercolleida_sesiones(id) ON DELETE SET NULL,
    anio SMALLINT,
    macho_frison NUMERIC(5,3),
    macho_cruzado NUMERIC(5,3),
    hembra_cruzada NUMERIC(5,3),
    ternero_pastero_frison NUMERIC(7,2),
    tendencia TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Cotizaciones de materias primas (Lonja de Lleida)
CREATE TABLE IF NOT EXISTS cotizaciones_materias_primas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id BIGINT REFERENCES mercolleida_sesiones(id) ON DELETE SET NULL,
    anio SMALLINT,
    mes TEXT,
    trigo_forrajero_eur_t NUMERIC(6,2),
    cebada_pienso_eur_t NUMERIC(6,2),
    maiz_importacion_eur_t NUMERIC(6,2),
    harina_soja_47_eur_t NUMERIC(6,2),
    alfalfa_deshidratada_eur_t NUMERIC(6,2),
    coste_medio_pienso_eur_t NUMERIC(6,2),
    coste_produccion_vivo_eur_kg NUMERIC(6,4),
    margen_neto_ganadero_eur_kg NUMERIC(6,4),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Pesos, sacrificios y producción
CREATE TABLE IF NOT EXISTS pesos_y_sacrificios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio SMALLINT,
    mes TEXT,
    peso_medio_vivo_kg NUMERIC(5,2),
    peso_medio_canal_kg NUMERIC(5,2),
    rendimiento_canal_pct NUMERIC(4,2),
    sacrificios_espana BIGINT,
    sacrificios_cataluna BIGINT,
    censo_espana BIGINT,
    exportaciones_china_t BIGINT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Series mensuales completas para ML
CREATE TABLE IF NOT EXISTS mercolleida_series_mensuales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mes TEXT NOT NULL,
    cerdo_normal_eur_kg NUMERIC(6,4),
    lechon_20kg_eur NUMERIC(6,2),
    peso_vivo_kg NUMERIC(5,2),
    sacrificios_espana BIGINT,
    trigo_eur_t NUMERIC(6,2),
    soja_eur_t NUMERIC(6,2),
    maiz_eur_t NUMERIC(6,2),
    cebada_eur_t NUMERIC(6,2),
    coste_pienso_eur_t NUMERIC(6,2),
    coste_produccion_eur_kg NUMERIC(6,4),
    margen_neto_eur_kg NUMERIC(6,4),
    var_mensual_cerdo_pct NUMERIC(5,2),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(mes)
);

-- 8. Dataset QA de instrucción/tuning para RAG
CREATE TABLE IF NOT EXISTS mercolleida_qa_tuning (
    id TEXT PRIMARY KEY,
    task_type TEXT,
    categoria TEXT,
    instruction TEXT NOT NULL,
    input_context TEXT,
    output_response TEXT NOT NULL,
    source_file TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Glosario y reglas de negocio (definiciones técnicas)
CREATE TABLE IF NOT EXISTS mercolleida_glosario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    termino_clave TEXT NOT NULL,
    seccion TEXT,
    definicion TEXT,
    formulas JSONB,
    parametros JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Correlaciones y benchmarks internacionales
CREATE TABLE IF NOT EXISTS mercolleida_correlaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mercado TEXT NOT NULL,
    unidad_cotizacion TEXT,
    factor_conversion_a_vivo NUMERIC(6,4),
    correlacion_r2 NUMERIC(4,3),
    dinamica_diferencial TEXT,
    elasticidad_pienso TEXT,
    break_even_data JSONB,
    source_file TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Índices para consultas frecuentes del ML
CREATE INDEX IF NOT EXISTS idx_cot_porcino_anio ON cotizaciones_porcino(anio);
CREATE INDEX IF NOT EXISTS idx_cot_lechon_anio ON cotizaciones_lechon(anio);
CREATE INDEX IF NOT EXISTS idx_series_mes ON mercolleida_series_mensuales(mes);
CREATE INDEX IF NOT EXISTS idx_sesiones_fecha ON mercolleida_sesiones(fecha_sesion);
CREATE INDEX IF NOT EXISTS idx_qa_task_type ON mercolleida_qa_tuning(task_type);
