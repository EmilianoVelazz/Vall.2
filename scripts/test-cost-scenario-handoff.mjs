import assert from 'node:assert/strict';
import {buildMarranasOrionHandoff,buildProteinOrionHandoff} from '../frontend/src/lib/orionHandoff.js';
import {calculateFeedCostScenarios} from '../shared/feed-cost-scenarios.mjs';
const spot={costPerSellable:40,grossMarginPct:null,totalBatchCost:400000};
const result=buildMarranasOrionHandoff({kind:'simulator',accountEmail:'fixture@example.invalid',row:{label:'Referencia sintética',unit:'MXN/kg vivo',basis:'Vivo'},horizon:{code:'1w',horizonLabel:'1 semana'},simulation:{volumeKg:10000,freightPerUnit:2.5,shrinkagePct:0,salePrice:null,usdMxn:20,annualFinancingPct:0,inventoryDays:0,scenarios:{currency:'MXN',spot,base:spot,stressP90:{costPerSellable:null,grossMarginPct:null},cashFlowDeltaBase:0,cashFlowDeltaStress:null}}});
assert(result.markdown.includes('falta precio de venta'));
assert(result.markdown.includes('USD/MXN efectivo 20.00'));
assert(result.markdown.includes('No calculado'));
assert(!/NaN|undefined|null|14\.0%/.test(result.markdown));
const assumptions={usdMxn:20,cornUnit:'USD/t',soyUnit:'USD/t',cornUsdTon:200,soymealUsdTon:350,cornSharePct:60,soySharePct:25,otherFeedMxnKg:4,feedConversionKg:2.7,operatingCostMxnKg:8,volumeKg:10000,fxShockPct:5,cornShockPct:10,soyShockPct:10};
const scenarios=calculateFeedCostScenarios(assumptions);
const feedHandoff=buildProteinOrionHandoff({kind:'feed-scenarios',simulation:{result:scenarios},accountEmail:'Feed.User@example.invalid'});
assert(scenarios.available);
assert.equal(feedHandoff.accountEmail,'feed.user@example.invalid');
assert.equal(feedHandoff.title,'Escenarios de Costo de Ración (Maíz + Soya × FCR)');
assert.equal(feedHandoff.reportKey,'feed_cost_scenarios');
assert(feedHandoff.markdown.startsWith(`# ${feedHandoff.title} (ORION ML)`));
assert(feedHandoff.markdown.includes('## Supuestos de ración (ingresados por el usuario)'));
assert(feedHandoff.markdown.includes('MXN/USD'));
assert(feedHandoff.markdown.includes('## Matriz de sensibilidad'));
assert(scenarios.rows.every(row=>feedHandoff.markdown.includes(row.label)));
const legacyBuilderHandoff=buildMarranasOrionHandoff({kind:'feed-scenarios',simulation:{result:scenarios},accountEmail:'Feed.User@example.invalid'});
assert.equal(feedHandoff.markdown,legacyBuilderHandoff.markdown);
assert.equal(feedHandoff.prompt,legacyBuilderHandoff.prompt);
assert.equal(feedHandoff.accountEmail,legacyBuilderHandoff.accountEmail);
console.log('Envío al chat: no falla sin precio de venta o banda; conserva unidades y supuestos explícitos.');
