'use strict';
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const express = require('express');
const jwt = require('jsonwebtoken');
process.env.JWT_SECRET = 'test-only-profile-recovery';
process.env.VERCEL = '1';
process.env.VALL_AUTH_EMAIL = 'admin@example.invalid';
const profiles = require('../backend/services/user-profile-store');
let active = true, unavailable = false, update;
profiles.findById = async () => { if (unavailable) throw Error('Simulated outage'); return null; };
profiles.findByEmail = async () => ({ id: 'remote-profile', email: process.env.VALL_AUTH_EMAIL, active, preferences: { otherFeature: true }, role: 'admin' });
profiles.updateProfile = async (id, patch) => { update = { id, patch }; return { email: process.env.VALL_AUTH_EMAIL, ...patch }; };
const { router } = require('../backend/routes/auth');
const app = express(); app.use(express.json()); app.use('/api', router);
const server = app.listen(0, '127.0.0.1');
(async () => {
  if (!server.listening) await new Promise(resolve => server.once('listening', resolve));
  const digest = crypto.createHash('sha256').update(`vall-admin:${process.env.VALL_AUTH_EMAIL}`).digest('hex');
  const sub = `${digest.slice(0,8)}-${digest.slice(8,12)}-4${digest.slice(13,16)}-a${digest.slice(17,20)}-${digest.slice(20,32)}`;
  const url = `http://127.0.0.1:${server.address().port}/api/profile`;
  const call = (claims, body) => fetch(url, { method: body ? 'POST' : 'GET', headers: { Authorization: `Bearer ${jwt.sign(claims, process.env.JWT_SECRET)}`, 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
  const claims = { sub, role: 'admin', email: process.env.VALL_AUTH_EMAIL };
  assert.equal((await call(claims)).status, 200, 'La sesión degradada recupera el perfil real');
  assert.equal((await call(claims, { preferences: { executiveReports: { depth: 'brief' } } })).status, 200);
  assert.equal(update.id, 'remote-profile'); assert.equal(update.patch.preferences.otherFeature, true);
  assert.equal(update.patch.preferences.executiveReports.depth, 'brief');
  assert.equal((await call({...claims,role:'user'})).status,401,'A missing regular profile invalidates the session before entering the profile route');
  assert.equal((await call({...claims,sub:'another-id'})).status,404);
  assert.equal((await call({...claims,email:'other@example.invalid'})).status,401,'A different administrator email must have an active profile');
  active = false; assert.equal((await call(claims)).status, 404, 'No reactiva perfiles deshabilitados');
  unavailable = true;
  const unavailableResponse = await call(claims);
  assert.equal(unavailableResponse.status, 503); assert.equal(unavailableResponse.headers.get('retry-after'), '5');
  console.log('Profile recovery: OK · sesión degradada y aislamiento de cuentas');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { server.closeAllConnections(); server.close(); });
